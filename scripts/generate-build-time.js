const fs = require('fs');
const path = require('path');

const now = new Date();
const epochSeconds = Math.floor(now.getTime() / 1000);

// Format as YYYY-MM-DD HH:mm:ss UTC
const pad = (num) => String(num).padStart(2, '0');
const year = now.getUTCFullYear();
const month = pad(now.getUTCMonth() + 1);
const day = pad(now.getUTCDate());
const hours = pad(now.getUTCHours());
const minutes = pad(now.getUTCMinutes());
const seconds = pad(now.getUTCSeconds());
const formattedUTC = `${year}-${month}-${day} ${hours}:${minutes}:${seconds} UTC`;

const content = `// This file is automatically generated during the build process.
// Do not edit this file manually.
export const BUILD_EPOCH = ${epochSeconds};
export const BUILD_DATE_UTC = "${formattedUTC}";
`;

const dir = path.join(__dirname, '../src');
if (!fs.existsSync(dir)) {
  fs.mkdirSync(dir, { recursive: true });
}

fs.writeFileSync(path.join(dir, 'build-time.ts'), content);
console.log(`[Build Time] Generated build-time.ts: ${epochSeconds} (${formattedUTC})`);
